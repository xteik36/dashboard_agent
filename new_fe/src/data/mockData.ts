export function getTaskItemById(taskId: string): TaskItem {
  // Check in critical tasks first
  if (CRITICAL_TASKS_DETAILED[taskId]) {
    return CRITICAL_TASKS_DETAILED[taskId];
  }
  // Check in attention tasks
  const fromAttention = ATTENTION_TASKS.find(
    (t) => t.id === taskId || t.title.toLowerCase().includes(taskId.toLowerCase())
  );
  if (fromAttention) {
    return fromAttention;
  }
  // Check in critical tasks list by name
  const fromCriticalList = CRITICAL_RISK_TASKS.find((c) => c.id === taskId);
  if (fromCriticalList) {
    return {
      id: fromCriticalList.id,
      title: fromCriticalList.name,
      subtitle: fromCriticalList.description,
      project: 'PMA Agent',
      sprint: fromCriticalList.sprint.replace('S', 'Sprint '),
      owner: fromCriticalList.owner,
      priority: 'Critical',
      status: fromCriticalList.isOverdue ? 'Overdue' : 'At Risk',
      progress: 60,
      dueDate: fromCriticalList.dueDate,
      blockerReason: fromCriticalList.description,
      subtasks: [
        { id: `st-${taskId}-1`, title: 'Review risk mitigation plan', completed: true },
        { id: `st-${taskId}-2`, title: 'Execute remediation fixes', completed: false },
        { id: `st-${taskId}-3`, title: 'Verify staging rollout', completed: false },
      ],
    };
  }
  // Default fallback
  return ATTENTION_TASKS[0];
}

